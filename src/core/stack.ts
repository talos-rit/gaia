import type { ComponentId, Config, PiCfg } from "./config.ts";

/**
 * Docker CLI prefix for a Pi. The lab Pis run an isolated daemon on /run/talos-docker.sock
 * (talos-docker.service, see operator/deploy/dual-arm/install-runtime.sh) so it can't disturb
 * the host's network/firewall setup; a stock install just uses `docker`.
 */
export function docker(pi: PiCfg): string {
  return pi.runtime === "isolated"
    ? `sudo -n ${pi.runtimeDir}/docker -H unix:///run/talos-docker.sock`
    : "sudo -n docker";
}

export function compose(pi: PiCfg): string {
  return pi.runtime === "isolated"
    ? `sudo -n env DOCKER_HOST=unix:///run/talos-docker.sock ${pi.runtimeDir}/docker-compose`
    : "sudo -n docker compose";
}

/** `cd` into the stack dir; compose picks up compose.yaml from there. */
export function inStack(cfg: Config, rest: string): string {
  return `cd ~/${cfg.stack.dir} && ${rest}`;
}

export function containerName(cfg: Config, svc: ComponentId): string {
  return `${cfg.stack.project}-${svc}-1`;
}

export const serialDevice = (pi: PiCfg) => `/dev/talos-${pi.id}-serial`;
export const cameraDevice = (pi: PiCfg) => `/dev/talos-${pi.id}-camera`;
export const rtspUrl = (pi: PiCfg, host = "127.0.0.1") => `rtsp://${host}:8554/${pi.arm.rtspPath}`;

export function operatorConf(pi: PiCfg): string {
  return [
    "log_loc: /logs/operator.log",
    "scorbot_dev: /dev/arm",
    "socket_address: 127.0.0.1",
    `socket_port: ${pi.arm.operatorPort}`,
    "",
  ].join("\n");
}

export function udevRules(pi: PiCfg): string | null {
  const usb = pi.arm.usb;
  if (!usb?.serial && !usb?.camera) return null;
  const lines = [`# Generated by Gaia for ${pi.name}. Matches physical USB ports; re-run "Detect USB devices" if rewired.`];
  if (usb.serial) {
    const ids = [usb.serial.vendor && `ATTRS{idVendor}=="${usb.serial.vendor}"`, usb.serial.product && `ATTRS{idProduct}=="${usb.serial.product}"`]
      .filter(Boolean)
      .join(", ");
    lines.push(
      `SUBSYSTEM=="tty", ENV{ID_PATH}=="${usb.serial.idPath}"${ids ? ", " + ids : ""}, SYMLINK+="talos-${pi.id}-serial", GROUP="dialout", MODE="0660", ENV{ID_MM_DEVICE_IGNORE}="1"`,
    );
  }
  if (usb.camera) {
    lines.push(
      `SUBSYSTEM=="video4linux", ENV{ID_PATH}=="${usb.camera.idPath}", ATTR{index}=="0", SYMLINK+="talos-${pi.id}-camera", GROUP="video", MODE="0660"`,
    );
  }
  return lines.join("\n") + "\n";
}

/** Settings for cam_streamer's scripts/stream_camera.sh (all env-driven). */
function cameraEnv(pi: PiCfg): Record<string, string> {
  const hw = pi.arm.encoder === "hardware";
  return {
    CAMERA_DEVICE: "/dev/camera",
    RTSP_PORT: "8554",
    STREAM_NAME: pi.arm.rtspPath,
    // The webcams only do 720p at 30 fps as MJPEG (YUYV tops out around 10 fps), so capture
    // MJPEG at 30 and let ffmpeg drop to 10 fps before encoding.
    INPUT_FORMAT: "mjpeg",
    VIDEO_SIZE: hw ? "1280x720" : "640x480",
    VIDEO_FPS: "30",
    OUTPUT_FPS: "10",
    VIDEO_ENCODER: hw ? "h264_v4l2m2m" : "libx264",
    VIDEO_BITRATE: hw ? "3M" : "1M",
  };
}

export type Images = Record<ComponentId, string>;

/**
 * The compose file Gaia writes to ~/<stack.dir>/compose.yaml on each Pi.
 * Mirrors the hand-written two-pi-20261104 stack (resource caps, SIGINT shutdown, no
 * auto-restart because Operator startup HOMEs the arm) but with one image per component.
 */
export function composeFile(cfg: Config, pi: PiCfg, images: Images): Record<string, unknown> {
  const base = (svc: ComponentId) => ({
    image: images[svc],
    network_mode: "host",
    restart: "no", // deliberate: an automatic Operator restart would HOME the arm unattended
    stop_signal: "SIGINT",
    stop_grace_period: "8s",
    security_opt: ["no-new-privileges:true"],
    logging: { driver: "json-file", options: { "max-size": "5m", "max-file": "2" } },
    labels: { "dev.talos.gaia.component": svc, "dev.talos.gaia.pi": pi.id },
  });
  const v = cfg.components.vision;
  return {
    name: cfg.stack.project,
    services: {
      operator: {
        ...base("operator"),
        environment: { ERV_CONTROLLER_PROFILE: pi.arm.controller },
        command: ["/opt/talos/erv", "/opt/talos/operator.conf"],
        devices: [`${serialDevice(pi)}:/dev/arm`],
        volumes: ["./operator.conf:/opt/talos/operator.conf:ro", "./logs:/logs"],
        cpus: 0.25,
        mem_limit: "32m",
        pids_limit: 128,
      },
      camera: {
        ...base("camera"),
        environment: cameraEnv(pi),
        devices: [`${cameraDevice(pi)}:/dev/camera`, ...(pi.arm.encoder === "hardware" ? ["/dev/video11:/dev/video11"] : [])],
        cpus: 0.75,
        mem_limit: "128m",
        pids_limit: 128,
      },
      vision: {
        ...base("vision"),
        depends_on: ["operator", "camera"],
        environment: {
          CAMERA_SOURCE: rtspUrl(pi),
          INFERENCE_FPS: String(pi.arm.inferenceFps),
          ...(v.env ?? {}),
        },
        command: [
          "python", "main.py",
          "--model", "/opt/talos/model.onnx",
          "--port", String(pi.arm.visionPort),
          // IPv4. pi-vision's uvicorn makes an IPv6-only socket for "::"; 0.0.0.0 is what the
          // pre-container systemd service used, and mDNS (bingo.local) clients fall back to IPv4.
          "--host", "0.0.0.0",
          "--operator-port", String(pi.arm.operatorPort),
          "--edge-control",
          ...(v.extraArgs ?? []),
        ],
        healthcheck: {
          test: ["CMD", "python", "-c", `import urllib.request; urllib.request.urlopen('http://localhost:${pi.arm.visionPort}/api/status', timeout=3)`],
          interval: "15s",
          timeout: "5s",
          retries: 3,
          start_period: "60s",
        },
        cpus: 2.5,
        mem_limit: "512m",
        pids_limit: 128,
      },
    },
  };
}

/**
 * Tiny YAML emitter. Every string is double-quoted (JSON string syntax is valid YAML), so values
 * like "::", "no", "8s" or "-b:v" can never be reinterpreted as mappings, booleans or numbers.
 * (Bun.YAML.stringify emitted `--host ::` as a bare `::`, which compose rejected.)
 */
export function toYaml(v: unknown, indent = 0): string {
  const pad = " ".repeat(indent);
  const key = (k: string) => (/^[A-Za-z_][\w.-]*$/.test(k) ? k : JSON.stringify(k));
  const scalar = (x: unknown) => (typeof x === "string" ? JSON.stringify(x) : x === null || x === undefined ? "null" : String(x));
  if (Array.isArray(v)) {
    if (!v.length) return "[]";
    return v.map((x) => (typeof x === "object" && x !== null ? `${pad}-\n${toYaml(x, indent + 2)}` : `${pad}- ${scalar(x)}`)).join("\n");
  }
  if (typeof v === "object" && v !== null) {
    const entries = Object.entries(v).filter(([, x]) => x !== undefined);
    if (!entries.length) return "{}";
    return entries
      .map(([k, x]) =>
        typeof x === "object" && x !== null && (Array.isArray(x) ? x.length : Object.keys(x).length)
          ? `${pad}${key(k)}:\n${toYaml(x, indent + 2)}`
          : `${pad}${key(k)}: ${typeof x === "object" && x !== null ? (Array.isArray(x) ? "[]" : "{}") : scalar(x)}`,
      )
      .join("\n");
  }
  return pad + scalar(v);
}

export function composeYaml(cfg: Config, pi: PiCfg, images: Images): string {
  return `# Generated by Gaia for ${pi.name}. Re-deploy from Gaia rather than editing by hand.\n` + toYaml(composeFile(cfg, pi, images)) + "\n";
}
