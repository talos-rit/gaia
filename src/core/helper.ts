import { createHash } from "node:crypto";
import { COMPONENTS, type Config, type PiCfg } from "./config.ts";
import type { RemoteStep } from "./jobs.ts";
import { cameraDevice, compose, docker, rtspUrl, serialDevice } from "./stack.ts";

/**
 * `talos`: a small helper script Gaia installs on every Pi (~/talos-stack/bin/talos, linked
 * from /usr/local/bin/talos). Every Gaia button runs one `talos <command>`, so the command
 * shown on hover is short, and after `ssh pi@bingo.local` you can type exactly the same thing.
 * `cat $(which talos)` shows what each command does.
 */
export const HELPER_PATH = "bin/talos"; // relative to ~/<stack.dir>

export function helperScript(cfg: Config, pi: PiCfg): string {
  const devs = [serialDevice(pi), cameraDevice(pi), ...(pi.arm.encoder === "hardware" ? ["/dev/video11"] : [])];
  const svcs = COMPONENTS.join(" ");
  return `#!/usr/bin/env bash
# talos: run the Talos container stack on ${pi.name}. Generated by Gaia (re-deploy to update).
# Gaia's buttons run these same commands over ssh.
set -uo pipefail

STACK="$HOME/${cfg.stack.dir}"
PROJECT=${cfg.stack.project}
RUNTIME=${pi.runtime}
DOCKER=(${docker(pi)})
COMPOSE=(${compose(pi)})
SERIAL=${serialDevice(pi)}
CAMERA=${cameraDevice(pi)}
DEVICES=(${devs.join(" ")})
SERVICES=(${svcs})
RTSP_URL=${rtspUrl(pi)}

usage() {
  cat <<'EOF'
usage: talos <command> [args]

Stack (one service, or all of them when no service is given):
  start [service]     start containers (starting operator HOMEs the arm)
  stop [service]      stop containers (kept for a quick start)
  restart [service]   restart containers in place
  down                remove the containers (images and logs stay)
  ps                  list the stack's containers
  logs <service> ...  container logs, e.g. talos logs vision -f --tail 100
  oplog ...           Operator's log file, e.g. talos oplog -F
  preflight           check devices are present and nothing else holds them
  snapshot > f.jpg    grab one JPEG frame from the camera stream

Troubleshooting:
  runtime             make sure Docker is running
  usb-detect          list USB serial adapters and cameras (for gaia.config.yaml)
  usb-rules < rules   install udev rules for the /dev/talos-* names, re-trigger udev
  owners              which processes hold the serial port / camera
  esp-reset           reset an ESP32 controller by pulsing the adapter's RTS line
  host-check          kernel, CMA, encoder, throttling, temperature, disk, memory
  kernel-log          kernel warnings since boot
  stop-legacy         stop the pre-container camera-streamer / pivision-integration units
  stop-foreign        stop containers that aren't part of this stack
  retire-host-mediamtx  stop + disable the host mediamtx.service (MediaMTX runs in the stack now)
  prune               delete dangling images

Escape hatches: talos docker ..., talos compose ...
Services: operator camera mediamtx vision
EOF
}

die() { echo "$*" >&2; exit 1; }
dc() { [ -f "$STACK/compose.yaml" ] || die "Nothing deployed in $STACK yet: use Deploy in Gaia first."; (cd "$STACK" && "\${COMPOSE[@]}" "$@"); }
check_svc() { for s in "$@"; do [[ " \${SERVICES[*]} " == *" $s "* ]] || die "unknown service '$s' (\${SERVICES[*]})"; done; }

runtime() {
  if [ "$RUNTIME" = isolated ]; then
    # The lab Pis' isolated daemon (talos-docker.service) isn't started at boot.
    systemctl is-active --quiet talos-docker.service || {
      echo "starting talos-docker.service"
      sudo -n systemctl start talos-docker.service
      for _ in $(seq 1 20); do [ -S /run/talos-docker.sock ] && break; sleep 1; done
    }
  else
    command -v docker >/dev/null || die "Docker isn't installed: use Troubleshoot > Install Docker in Gaia."
  fi
  "\${DOCKER[@]}" info --format 'docker {{.ServerVersion}} is up' || die "Docker isn't answering."
}

preflight() {
  local fail=0 d u others
  for d in "\${DEVICES[@]}"; do
    if [ -e "$d" ]; then echo "ok        $d -> $(readlink -f "$d")"
    else echo "MISSING   $d  (unplugged? try Troubleshoot > Re-apply USB rules)"; fail=1; fi
  done
  for u in camera-streamer.service pivision-integration.service; do
    if systemctl is-active --quiet "$u"; then echo "CONFLICT  legacy host service $u is running (talos stop-legacy)"; fail=1; fi
  done
  if systemctl is-active --quiet mediamtx.service; then
    echo "CONFLICT  host mediamtx.service holds the RTSP port; MediaMTX now runs in the stack (talos retire-host-mediamtx)"; fail=1
  fi
  others=$("\${DOCKER[@]}" ps --format '{{.Names}} {{.Label "com.docker.compose.project"}}' | awk -v p="$PROJECT" '$2!=p{print $1}' | tr '\\n' ' ')
  if [ -n "$others" ]; then echo "CONFLICT  other containers running: $others(talos stop-foreign)"; fail=1; fi
  [ $fail = 0 ] && echo "preflight passed"
  return $fail
}

cmd=\${1:-help}
shift || true
case "$cmd" in
  start|up)
    runtime >/dev/null || exit 1
    if [ $# -gt 0 ]; then check_svc "$@"; dc up -d --no-deps "$@"
    else preflight && dc up -d --remove-orphans; fi ;;
  stop)     check_svc "$@"; dc stop "$@" ;;
  restart)  check_svc "$@"; runtime >/dev/null || exit 1; dc restart "$@" ;;
  down)     dc down ;;
  ps)       "\${DOCKER[@]}" ps -a --filter "label=com.docker.compose.project=$PROJECT" ;;
  logs)     [ $# -gt 0 ] || die "usage: talos logs <service> [docker logs options]"
            svc=$1; shift; check_svc "$svc"; exec "\${DOCKER[@]}" logs "$@" "$PROJECT-$svc-1" ;;
  oplog)    exec tail "$@" "$STACK/logs/operator.log" ;;
  preflight) preflight ;;
  snapshot)
    grab=(-v error -rtsp_transport tcp -i "$RTSP_URL" -frames:v 1 -q:v 4 -f image2 -c:v mjpeg -)
    if command -v ffmpeg >/dev/null; then exec timeout 10 ffmpeg "\${grab[@]}"
    else exec timeout 10 "\${DOCKER[@]}" exec "$PROJECT-camera-1" ffmpeg "\${grab[@]}"; fi ;;
  runtime)  runtime ;;
  usb-detect)
    for d in /dev/ttyUSB* /dev/ttyACM* /dev/video*; do
      [ -e "$d" ] || continue
      p=$(udevadm info -q property -n "$d"); idp=$(echo "$p" | sed -n 's/^ID_PATH=//p')
      case "$idp" in *usb*) ;; *) continue ;; esac
      echo "$d  ID_PATH=$idp  vendor=$(echo "$p" | sed -n 's/^ID_VENDOR_ID=//p') product=$(echo "$p" | sed -n 's/^ID_MODEL_ID=//p')  $(echo "$p" | sed -n 's/^ID_MODEL=//p')"
    done
    echo; ls -l /dev/talos-* 2>/dev/null || echo "no /dev/talos-* aliases present" ;;
  usb-rules)
    [ -t 0 ] && die "usage: talos usb-rules < rules-file   (Gaia sends the generated rules)"
    sudo -n tee /etc/udev/rules.d/70-talos-gaia.rules >/dev/null &&
      sudo -n udevadm control --reload-rules &&
      sudo -n udevadm trigger --action=add --subsystem-match=tty &&
      sudo -n udevadm trigger --action=add --subsystem-match=video4linux &&
      sudo -n udevadm settle && ls -l /dev/talos-* ;;
  owners)   sudo -n fuser -v "$SERIAL" "$CAMERA" 2>&1 || echo "(no process has them open)" ;;
  esp-reset)
    sudo -n python3 - "$SERIAL" <<'EOF'
import fcntl, os, struct, sys, time
fd = os.open(sys.argv[1], os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
TIOCMBIS, TIOCMBIC, DTR, RTS = 0x5416, 0x5417, 0x002, 0x004
fcntl.ioctl(fd, TIOCMBIC, struct.pack("I", DTR)); fcntl.ioctl(fd, TIOCMBIS, struct.pack("I", RTS))
time.sleep(0.2); fcntl.ioctl(fd, TIOCMBIC, struct.pack("I", RTS)); time.sleep(1.5)
os.close(fd); print("reset pulsed")
EOF
    ;;
  host-check)
    echo "kernel:    $(uname -r)"
    echo "cma:       $(awk '/^CmaTotal:/{print $2/1024 " MiB"}' /proc/meminfo)   (the hardware encoder needs >= 256)"
    echo "encoder:   $([ -e /dev/video11 ] && echo /dev/video11 present || echo /dev/video11 MISSING)"
    echo "throttled: $(vcgencmd get_throttled 2>/dev/null || echo n/a)   (0x0 = never throttled)"
    echo "temp:      $(vcgencmd measure_temp 2>/dev/null || echo n/a)"
    echo "uptime:   $(uptime)"; echo; free -h; echo; df -h / | tail -n 1; echo
    for u in docker.service talos-docker.service mediamtx.service; do echo "$u: $(systemctl is-active $u 2>&1)"; done ;;
  kernel-log) sudo -n journalctl -k -b -p warning --no-pager | tail -n 120 ;;
  stop-legacy)
    sudo -n systemctl stop camera-streamer.service pivision-integration.service 2>&1
    systemctl is-active camera-streamer.service pivision-integration.service; true ;;
  stop-foreign)
    for c in $("\${DOCKER[@]}" ps --format '{{.Names}} {{.Label "com.docker.compose.project"}}' | awk -v p="$PROJECT" '$2!=p{print $1}'); do
      echo "stopping $c"; "\${DOCKER[@]}" stop -t 8 "$c"
    done; echo done ;;
  retire-host-mediamtx)
    if systemctl is-enabled --quiet mediamtx.service 2>/dev/null || systemctl is-active --quiet mediamtx.service; then
      sudo -n systemctl disable --now mediamtx.service && echo "host mediamtx.service stopped and disabled (undo: sudo systemctl enable --now mediamtx)"
    else echo "host mediamtx.service is not in use"; fi ;;
  prune)    "\${DOCKER[@]}" image prune -f && "\${DOCKER[@]}" system df && df -h / | tail -n 1 ;;
  docker)   exec "\${DOCKER[@]}" "$@" ;;
  compose)  dc "$@" ;;
  help|-h|--help) usage ;;
  *)        usage >&2; exit 2 ;;
esac
`;
}

export const helperHash = (cfg: Config, pi: PiCfg) => createHash("sha256").update(helperScript(cfg, pi)).digest("hex");

/** Install or update the helper (content arrives on stdin, so the command stays short). */
export function installHelperStep(cfg: Config, pi: PiCfg): RemoteStep {
  const p = `~/${cfg.stack.dir}/${HELPER_PATH}`;
  return {
    label: "Install/update the talos helper on the Pi",
    where: "remote",
    cmd: `mkdir -p ~/${cfg.stack.dir}/bin && cat > ${p} && chmod 0755 ${p} && sudo -n ln -sfn ${p.replace("~", "$HOME")} /usr/local/bin/talos && echo "talos helper installed"`,
    stdin: helperScript(cfg, pi),
    stdinNote: "generated talos script (see More › Generated files)",
  };
}

/** `talos <args>`: what Gaia's buttons run. */
export const talos = (args: string) => `talos ${args}`;
